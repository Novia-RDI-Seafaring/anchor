import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";
import tailwind from "@tailwindcss/postcss";

const web = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = path.join(web, "src/intent-overlay/styles.source.css");
const output = path.join(web, "src/intent-overlay/styles.css");
const compiled = await postcss([tailwind()]).process(await fs.readFile(source, "utf8"), { from: source });
const scope = ":where([data-intent-overlay])";
compiled.root.walkRules((rule) => {
  for (let ancestor = rule.parent; ancestor; ancestor = ancestor.parent) {
    if (ancestor.type === "rule") return; // Nested '&' already inherits the scoped selector.
  }
  if (rule.parent?.type === "atrule" && /keyframes$/.test(rule.parent.name)) return;
  rule.selectors = [...new Set(rule.selectors.map((selector) => {
    if (selector === ":root" || selector === ":host") return scope;
    return `${scope} ${selector}`;
  }))];
});
const base = `${scope} { display: contents; font-family: ui-sans-serif, system-ui, sans-serif; line-height: 1.5; }
${scope} *, ${scope} *::before, ${scope} *::after { box-sizing: border-box; }
${scope} button, ${scope} input, ${scope} textarea { font: inherit; color: inherit; margin: 0; padding: 0; border: 0 solid; background-color: transparent; }
${scope} button { cursor: pointer; }
${scope} textarea { resize: none; }
${scope} table { border-collapse: collapse; }
${scope} ul, ${scope} ol { list-style: none; margin: 0; padding: 0; }
${scope}[data-pen-up] * { pointer-events: none !important; }
`;
// Keep the stylesheet explicit and portable, without global Tailwind preflight.
await fs.writeFile(output, `/* Generated by scripts/build-intent-overlay-css.mjs. */\n${compiled.root.toString()}\n${base}`, "utf8");
